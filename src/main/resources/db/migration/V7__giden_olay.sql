-- V7: Giden olay kutusu (transactional outbox).
--
-- Bildirim, onay commit olduktan SONRA ayri bir transaction'da yaziliyordu. Ikisinin
-- arasinda uygulama kapanirsa bildirim iz birakmadan kayboluyordu: olay yalnizca
-- bellekteydi. Olay artik talep ve denetim kaydiyla ayni transaction'da bu tabloya
-- yaziliyor; isleyici onu buradan okuyup bildirimi uretiyor (bkz. docs/decisions.md K-023).
--
-- Olayin alanlari JSON degil kolon: tek olay tipi var ve tipleri veritabani biliyor.
--
-- onceki_durum ve yeni_durum icin bilerek CHECK yok. Deger listesi zaten onay_kaydi'nda
-- denetleniyor; burada tekrarlansaydi yeni bir durum eklenirken unutulan ikinci liste,
-- hic ilgisi olmayan onay islemini geri sarardi. Kolon genislikleri de ayni sebeple
-- kaynak kolonlarla ayni.

CREATE TABLE giden_olay (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    talep_id            BIGINT       NOT NULL,
    talep_basligi       VARCHAR(200) NOT NULL,
    onceki_durum        VARCHAR(20)  NOT NULL,
    yeni_durum          VARCHAR(20)  NOT NULL,
    islem_yapan_id      BIGINT       NOT NULL,
    talep_sahibi_id     BIGINT       NOT NULL,
    birim_id            BIGINT       NOT NULL,
    durum               VARCHAR(20)  NOT NULL,
    deneme_sayisi       INTEGER      NOT NULL,
    sonraki_deneme      TIMESTAMPTZ  NOT NULL,
    islenme_tarihi      TIMESTAMPTZ,
    son_hata            VARCHAR(500),
    olusturma_tarihi    TIMESTAMPTZ  NOT NULL,
    guncelleme_tarihi   TIMESTAMPTZ  NOT NULL,
    olusturan_kullanici VARCHAR(60)  NOT NULL,
    CONSTRAINT fk_giden_olay_talep        FOREIGN KEY (talep_id)        REFERENCES talep (id),
    CONSTRAINT fk_giden_olay_islem_yapan  FOREIGN KEY (islem_yapan_id)  REFERENCES kullanici (id),
    CONSTRAINT fk_giden_olay_talep_sahibi FOREIGN KEY (talep_sahibi_id) REFERENCES kullanici (id),
    CONSTRAINT fk_giden_olay_birim        FOREIGN KEY (birim_id)        REFERENCES birim (id),
    CONSTRAINT ck_giden_olay_durum   CHECK (durum IN ('BEKLIYOR', 'ISLENDI', 'BASARISIZ')),
    CONSTRAINT ck_giden_olay_islenme CHECK ((durum = 'ISLENDI') = (islenme_tarihi IS NOT NULL))
);

COMMENT ON TABLE giden_olay IS
    'Talep ile ayni transaction''da yazilan, sonra islenen olaylar. Islenen satir silinmez, isaretlenir.';

-- Isleyici birkac saniyede bir bu sorguyu atiyor. Kismi indeks yalnizca bekleyenleri
-- kapsiyor, boylece islenmis satirlar biriktikce yoklama yavaslamiyor.
CREATE INDEX ix_giden_olay_bekleyen ON giden_olay (sonraki_deneme) WHERE durum = 'BEKLIYOR';
